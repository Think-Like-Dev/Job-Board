import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Transform, Type, type TransformFnParams } from 'class-transformer';
import {
  IsArray,
  IsBoolean,
  IsEnum,
  IsIn,
  IsInt,
  IsNotEmpty,
  IsOptional,
  IsString,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';
import {
  CompensationType,
  EmploymentType,
  JobStatus,
  WorkMode,
} from '@common/constants/enums';

const CREATE_JOB_STATUSES: JobStatus[] = [JobStatus.DRAFT, JobStatus.PUBLISHED];

const SALARY_PERIODS = ['Yearly', 'Monthly', 'Hourly'] as const;

export class CompensationDto {
  @ApiProperty({ enum: CompensationType })
  @IsEnum(CompensationType)
  type!: CompensationType;

  @ApiPropertyOptional({ example: '$ USD' })
  @IsString()
  @IsOptional()
  currency?: string;

  @ApiPropertyOptional({ enum: SALARY_PERIODS })
  @IsIn(SALARY_PERIODS)
  @IsOptional()
  period?: (typeof SALARY_PERIODS)[number];

  // FIXED uses a number, RANGE uses [min, max]; shape is validated in the service.
  @ApiPropertyOptional({
    oneOf: [{ type: 'number' }, { type: 'array', items: { type: 'number' } }],
  })
  @IsOptional()
  amount?: number | number[];
}

export class ApplicationSettingsDto {
  @ApiProperty()
  @IsBoolean()
  coverLetterRequired!: boolean;

  @ApiProperty()
  @IsBoolean()
  attachmentsAllowed!: boolean;

  @ApiProperty({ minimum: 0 })
  @IsInt()
  @Min(0)
  maximumAttachments!: number;
}

/**
 * Create-job payload sent by the recruiter wizard. README-mandatory fields are
 * optional here so drafts can be saved early; the service enforces them when
 * `status` is PUBLISHED.
 */
export class CreateJobDto {
  @ApiPropertyOptional({ description: 'Generated by the server when omitted' })
  @IsString()
  @IsOptional()
  code?: string;

  @ApiProperty({ example: 'Senior Backend Engineer' })
  @Transform(({ value }: TransformFnParams): unknown =>
    typeof value === 'string' ? value.trim() : value,
  )
  @IsString()
  @IsNotEmpty()
  @MaxLength(255)
  title!: string;

  @ApiPropertyOptional()
  @IsString()
  @IsOptional()
  department?: string;

  @ApiPropertyOptional()
  @IsString()
  @IsOptional()
  designation?: string;

  @ApiPropertyOptional({ description: 'Required when publishing' })
  @IsString()
  @IsOptional()
  category?: string;

  @ApiProperty({ enum: EmploymentType })
  @IsEnum(EmploymentType)
  employmentType!: EmploymentType;

  @ApiPropertyOptional({ description: 'Required when publishing' })
  @IsString()
  @IsOptional()
  location?: string;

  @ApiPropertyOptional({ description: 'Required when publishing' })
  @IsString()
  @IsOptional()
  description?: string;

  @ApiPropertyOptional()
  @IsString()
  @IsOptional()
  responsibilities?: string;

  @ApiPropertyOptional({ example: '3-5 years' })
  @IsString()
  @IsOptional()
  yearsOfExperience?: string;

  @ApiPropertyOptional({
    type: [String],
    enum: WorkMode,
    isArray: true,
    description: 'Required when publishing',
  })
  @IsArray()
  @IsEnum(WorkMode, { each: true })
  @IsOptional()
  workMode?: WorkMode[];

  @ApiPropertyOptional({
    type: [String],
    description: 'Required when publishing',
  })
  @IsArray()
  @IsString({ each: true })
  @IsOptional()
  skills?: string[];

  @ApiPropertyOptional({ type: [String] })
  @IsArray()
  @IsString({ each: true })
  @IsOptional()
  keywords?: string[];

  @ApiPropertyOptional({ type: [String] })
  @IsArray()
  @IsString({ each: true })
  @IsOptional()
  benefits?: string[];

  @ApiPropertyOptional({ type: [String] })
  @IsArray()
  @IsString({ each: true })
  @IsOptional()
  workShiftTiming?: string[];

  @ApiPropertyOptional({ type: CompensationDto, nullable: true })
  @ValidateNested()
  @Type(() => CompensationDto)
  @IsOptional()
  compensation?: CompensationDto | null;

  @ApiPropertyOptional({ minimum: 1, default: 1 })
  @IsInt()
  @Min(1)
  @IsOptional()
  vacancies?: number;

  @ApiPropertyOptional({
    minimum: 1,
    description: 'Required when publishing',
  })
  @IsInt()
  @Min(1)
  @IsOptional()
  totalInterviewRounds?: number;

  @ApiPropertyOptional({
    example: '2026-12-31',
    description: 'Required when publishing',
  })
  @IsString()
  @IsOptional()
  lastApplicationDate?: string;

  @ApiPropertyOptional({ type: ApplicationSettingsDto })
  @ValidateNested()
  @Type(() => ApplicationSettingsDto)
  @IsOptional()
  applicationSettings?: ApplicationSettingsDto;

  @ApiProperty({
    enum: CREATE_JOB_STATUSES,
    description:
      'DRAFT saves partial data; PUBLISHED requires mandatory fields',
  })
  @IsIn(CREATE_JOB_STATUSES)
  status!: JobStatus;
}
